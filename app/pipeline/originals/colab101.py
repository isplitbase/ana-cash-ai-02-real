# 不整合自動検知・修正（validate_and_fix_data）
# ==================================================================
def validate_and_fix_data(data_dict, closing_dates):
    """
    CF計算前にdata_dictの不整合を検知し、可能な範囲で自動修正する。

    検知・修正項目:
      [1] B/S借方貸方不一致（資産合計 ≠ 負債・純資産合計）→ アラートのみ
      [2] P/L当期純利益 ≠ data_dict[154]               → data_dict[154]を自動修正
      [3] CF照合差 c50 がゼロでない                      → |差|≦5円は端数注記、>5円はアラート

    Returns:
        alerts: list[str]  警告メッセージ（HTML表示用）
        fixes:  list[str]  自動修正ログ（HTML表示用）
    """
    alerts = []
    fixes  = []
    PERIODS = ['前々期', '前期', '今期']

    name_idx = _build_name_index(data_dict)

    def _v(name, period):
        rn = name_idx.get(name)
        if rn is None: return None
        v = data_dict.get(rn, {}).get(period, 0)
        try: return float(v) if v not in (None, '', '""') else 0.0
        except: return 0.0

    def _dd(rn, period):
        v = data_dict.get(rn, {}).get(period, 0)
        try: return float(v) if v not in (None, '', '""') else 0.0
        except: return 0.0

    def _ff(key_list, period):
        return _acct_first(name_idx, data_dict, key_list, period)

    # ──────────────────────────────────────────────────────
    # [1] B/S借方貸方の不一致
    # ──────────────────────────────────────────────────────
    for p in PERIODS:
        asset      = _ff(_ACCT['現金'], p)  # 資産合計を探す
        asset_rn   = name_idx.get('資産合計')
        liab_rn    = name_idx.get('負債・純資産合計（負債・資本合計）') or \
                     name_idx.get('負債純資産合計') or \
                     name_idx.get('負債・資本合計')
        if asset_rn and liab_rn:
            asset_v = _dd(asset_rn, p)
            liab_v  = _dd(liab_rn, p)
            diff = int(asset_v - liab_v)
            if diff != 0:
                alerts.append(
                    f'[B/S不一致][{p}] 資産合計={int(asset_v):,} '
                    f'vs 負債・純資産合計={int(liab_v):,} → 差={diff:+,}円 '
                    f'（読取精度の問題の可能性。自動修正不可）'
                )

    # ──────────────────────────────────────────────────────
    # [2] P/L当期純利益 ≠ data_dict[154]
    # ──────────────────────────────────────────────────────
    pl_names = ['当期純利益', '当期利益', '税引後当期純利益', '当期純損益']
    for p in PERIODS:
        pl_val = None
        pl_name_found = None
        for nm in pl_names:
            v = _v(nm, p)
            if v is not None:
                pl_val = v; pl_name_found = nm; break

        dd154_val = _dd(154, p)

        if pl_val is not None:
            diff = int(pl_val - dd154_val)
            if diff != 0:
                # 自動修正: data_dict[154] を P/L値で上書き
                if 154 not in data_dict:
                    data_dict[154] = {'行番号': 154, '勘定科目': '当期純利益'}
                data_dict[154][p] = pl_val
                fixes.append(
                    f'[P/L修正][{p}] data_dict[154]({p})を '
                    f'{int(dd154_val):,} → {int(pl_val):,} に修正 '
                    f'（参照科目: {pl_name_found}）'
                )

    # ──────────────────────────────────────────────────────
    # [3] CF照合差（c50）の確認
    #     ※ calc_cf_from_data_dict を呼んで確認
    # ──────────────────────────────────────────────────────
    try:
        _cf_check = calc_cf_from_data_dict(data_dict, closing_dates)
        for period_key, cf_dict, label in [
            ('前期', _cf_check['zenki'], '前期'),
            ('今期', _cf_check['konki'], '今期'),
        ]:
            c50 = cf_dict.get('c50', 0)
            c48 = cf_dict.get('c48', 0)
            c49 = cf_dict.get('c49', 0)
            if c50 == 0:
                continue
            elif abs(c50) <= 5:
                fixes.append(
                    f'[CF端数][{label}] 照合差={c50:+,}円 '
                    f'（千円単位の端数誤差。許容範囲内）'
                )
            else:
                # 原因特定: 各セクション合計 vs B/S変動で差異の所在を特定
                c24 = cf_dict.get('c24', 0)
                c36 = (cf_dict.get('c28',0)+cf_dict.get('c29',0)+cf_dict.get('c30',0)
                       +cf_dict.get('c31',0)+cf_dict.get('c34',0)+cf_dict.get('c35',0))
                c45 = cf_dict.get('c45', 0)
                alerts.append(
                    f'[CF不一致][{label}] 照合差={c50:+,}円 '
                    f'（Ⅵ期末={c48:,} vs B/S現金={c49:,}）'
                    f' | Ⅰ={c24:,} Ⅱ={c36:,} Ⅲ={c45:,}'
                )
    except Exception as _e:
        alerts.append(f'[CF検証エラー] {_e}')

    return alerts, fixes


def format_validation_log(alerts, fixes):
    """アラート・修正ログをHTML形式で返す"""
    if not alerts and not fixes:
        return ''
    parts = []
    if fixes:
        parts.append(
            '<div style="background:#d4edda;border:1px solid #c3e6cb;'
            'border-radius:4px;padding:8px 12px;margin:6px 0;font-size:11px;">'
            '<b>✅ 自動修正（' + str(len(fixes)) + '件）</b><br>'
            + '<br>'.join(fixes) + '</div>'
        )
    if alerts:
        parts.append(
            '<div style="background:#fff3cd;border:1px solid #ffc107;'
            'border-radius:4px;padding:8px 12px;margin:6px 0;font-size:11px;">'
            '<b>⚠️ 要確認アラート（' + str(len(alerts)) + '件）</b><br>'
            + '<br>'.join(alerts) + '</div>'
        )
    return ''.join(parts)


# ==================================================================
# データ不整合の検知・警告層（detect_data_anomalies）
# CF計算の手前で入力データの不整合を検出して報告する。
# 修復は行わず検知・警告に徹する（人間判断のための材料提供）。
#   A: 現金・流動資産の重複読み取り（同一口座の二重計上）
#   C: 販管費内訳の欠落（内訳ページが読み取れず費目が丸められる）
#   D: 製造原価の誤混入（商品売買業に別書類の製造原価が混入）
# ==================================================================

def detect_data_anomalies(data_dict, closing_dates, extra=None):
    """
    入力データの不整合を検知する。
    extra: {'販売費':[...], '製造原価':[...]} 等の内訳データ（任意）
    戻り値: list[dict]  各異常の詳細
    """
    def _dn(v):
        try:
            return float(str(v).replace(',', '')) if v not in (None, '', '""', '　') else 0.0
        except:
            return 0.0

    p_from = closing_dates.get('前期', '前期')
    p_to = closing_dates.get('今期', '今期')
    anomalies = []
    rows = list(data_dict.values())

    def _v(row, p):
        return _dn(row.get(p, 0))

    def _find_row(name):
        for r in rows:
            if str(r.get('勘定科目', '')).strip() == name:
                return r
        return None

    def _is_agg(name):
        return any(k in name for k in ['合計', '計']) or name.endswith('の部')

    _SUBTOTAL_NAMES = {
        '当座資産', '棚卸資産', 'その他流動資産', 'その他の流動資産',
        '有形固定資産', '無形固定資産', '投資その他の資産', '投資その他資産',
        '繰延資産', '引当金の部',
    }

    def _has_detail_under(subtotal_name, section):
        for r in rows:
            nm = str(r.get('勘定科目', '')).strip()
            sc = str(r.get('分類', '') or r.get('section', '')).strip()
            if sc == section and nm != subtotal_name and nm not in _SUBTOTAL_NAMES \
               and nm != '流動資産' and not _is_agg(nm):
                return True
        return False

    # ── 【A】現金・流動資産の重複読み取り ──────────────
    ryudo_total = _find_row('流動資産合計') or _find_row('流動資産')
    if ryudo_total:
        for period in [p_from, p_to]:
            total = _v(ryudo_total, period)
            meisai = 0.0
            detail_rows = []
            for r in rows:
                name = str(r.get('勘定科目', '')).strip()
                sec = str(r.get('分類', '') or r.get('section', '')).strip()
                if not name or name == '流動資産' or _is_agg(name):
                    continue
                if name in _SUBTOTAL_NAMES and _has_detail_under(name, sec):
                    continue
                if sec == '流動資産' or ('流動資産' in sec and '合計' not in sec):
                    val = _v(r, period)
                    if val != 0:
                        meisai += val
                        detail_rows.append((name, val))
            diff = meisai - total
            if abs(diff) > 0.5:
                dup = []
                for i in range(len(detail_rows)):
                    for j in range(i + 1, len(detail_rows)):
                        n1, v1 = detail_rows[i]
                        n2, v2 = detail_rows[j]
                        if abs(v1 - v2) < 0.5 and abs(v1 - diff) < 0.5:
                            dup.append((n1, n2, v1))
                # 差額と一致する同額ペアがある場合のみ報告（誤検知回避）
                if dup:
                    n1, n2, v = dup[0]
                    anomalies.append({
                        'type': 'A', 'severity': 'warning',
                        'title': '現金・流動資産の重複読み取りの疑い',
                        'detail': f'{period}: 明細合計({meisai:,.0f})と流動資産合計({total:,.0f})の差が{diff:,.0f}。'
                                  f'同額の「{n1}」「{n2}」(各{v:,.0f})が重複読み取りの可能性。',
                        'suggestion': f'「{n1}」または「{n2}」のいずれかが同一口座の二重計上でないか確認してください。',
                        'items': [n1, n2],
                    })

    # ── 【D】製造原価の誤混入 ──────────────────────
    if extra and '製造原価' in extra and extra['製造原価']:
        sei = extra['製造原価']
        sei_total = sum(_dn(r.get(p_to, {}).get('金額') if isinstance(r.get(p_to), dict) else r.get(p_to)) for r in sei)
        uriage = _find_row('売上原価') or _find_row('【売上原価】')
        has_shohin = (_find_row('期首商品棚卸高') or _find_row('期首製品・商品棚高')
                      or _find_row('期末商品棚卸高') or _find_row('期末製品・商品棚卸高'))
        if uriage is not None:
            ug = _v(uriage, p_to)
            if sei_total > 0 and ug > 0 and sei_total > ug * 3 and has_shohin:
                anomalies.append({
                    'type': 'D', 'severity': 'warning',
                    'title': '製造原価の誤混入の疑い',
                    'detail': f'製造原価合計({sei_total:,.0f})が売上原価({ug:,.0f})の3倍超。'
                              f'かつ商品売買業の兆候（商品棚卸あり）。別書類の製造原価が混入した可能性。',
                    'suggestion': '商品売買業のデータに製造原価ページが誤混入していないか、帳票のページ分類を確認してください。',
                    'items': [],
                })

    # ── 【C】販管費内訳の欠落 ──────────────────────
    if extra and '販売費' in extra and extra['販売費']:
        han = extra['販売費']

        def _hv(r, pk):
            v = r.get(pk, {})
            return _dn(v.get('金額') if isinstance(v, dict) else v)

        def _count(pk):
            cnt = 0
            maxi = 0.0
            for r in han:
                name = str(r.get('勘定科目', '')).strip()
                if name == '販売費及び一般管理費' or '合計' in name:
                    continue
                val = _hv(r, pk)
                if val != 0:
                    cnt += 1
                    maxi = max(maxi, abs(val))
            return cnt, maxi

        cnt_from, max_from = _count(p_from)
        cnt_to, max_to = _count(p_to)
        pl_hankan = _find_row('販売費及び一般管理費')
        pl_from = _v(pl_hankan, p_from) if pl_hankan else 0
        pl_to = _v(pl_hankan, p_to) if pl_hankan else 0

        for lp, cnt, maxi, pl_val, other in [
            (p_from, cnt_from, max_from, pl_from, cnt_to),
            (p_to, cnt_to, max_to, pl_to, cnt_from),
        ]:
            if pl_val != 0 and cnt <= 2 and other >= 5:
                conc = (maxi / abs(pl_val) * 100) if pl_val else 0
                anomalies.append({
                    'type': 'C', 'severity': 'warning',
                    'title': '販管費内訳の欠落の疑い',
                    'detail': f'{lp}: PL本体の販管費は{pl_val:,.0f}円だが、内訳の費目が{cnt}件しかありません'
                              f'（他期は{other}件）。',
                    'suggestion': f'{lp}の販管費内訳ページが読み取れていない可能性があります。'
                                  f'減価償却費など個別費目がCFに反映されないため、内訳ページの読み取りを確認してください。',
                    'items': [],
                })

    return anomalies


